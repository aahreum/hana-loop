-- ────────────────────────────────────────────────────────────
-- Emission Results  (seed 시점 계산값)
-- emission_kg_co2e = quantity × factor
-- ────────────────────────────────────────────────────────────
INSERT INTO emission_results
  (activity_id, factor_id, company_id, year_month, quantity, factor, emission_kg_co2e, scope)
SELECT
  a.id,
  ef.id,
  a.company_id,
  a.year_month,
  a.quantity,
  ef.factor,
  ROUND(a.quantity * ef.factor, 6),
  a.scope
FROM activities a
JOIN emission_factors ef
  ON ef.category = a.factor_category
 AND ef.valid_to IS NULL;
